#!/usr/bin/env python3
"""Extracts pure functions VERBATIM from AppKit/ScreenCaptureKit-bound app
files and wraps them in their real type names for the harness:

  ContextCapture.swift  -> truncate + omissionMarker + snapBackward/snapForward/tailSample/headSample
  ScreenCapturer.swift  -> maxLongEdge + displayIndex

Extraction is mechanical (brace-matched, by function name) and runs on
every sync, so the harness always tests the app's current code — there is
no hand-maintained copy to drift."""
import re
import sys

JOBS = [
    ("../../Wisp/Capture/ContextCapture.swift",
     "Sources/WispCore/ContextCaptureExtract.swift",
     "ContextCapture",
     ["truncate", "omissionMarker", "snapBackward", "snapForward", "tailSample", "headSample"]),
    ("../../Wisp/Capture/ScreenCapturer.swift",
     "Sources/WispCore/ScreenCapturerExtract.swift",
     "ScreenCapturer",
     ["maxLongEdge", "displayIndex"]),
]

def extract(lines, name, source):
    start = None
    for i, line in enumerate(lines):
        if re.search(rf"\bfunc {name}\(", line):
            start = i
            break
    if start is None:
        sys.exit(f"extract: function {name} not found in {source}")
    depth = 0
    for j in range(start, len(lines)):
        depth += lines[j].count("{") - lines[j].count("}")
        if j > start and depth == 0:
            return "\n".join(lines[start:j + 1])
    sys.exit(f"extract: unbalanced braces in {name}")

for source, dest, type_name, wanted in JOBS:
    lines = open(source, encoding="utf-8").read().split("\n")
    body = "\n\n".join(extract(lines, name, source) for name in wanted)
    header = f"""import Foundation

// GENERATED by extract-context-capture.py on every sync — do not edit.
// Verbatim function bodies from {source.split('Wisp/')[1]} (the rest of
// that file is platform-bound; see README).
enum {type_name} {{
"""
    open(dest, "w", encoding="utf-8").write(header + body + "\n}\n")
    print(f"extracted {len(wanted)} functions -> {dest}")
